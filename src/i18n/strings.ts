/** Zone names reported by drivers, translated where we know them. */
const ZONES_SK: [RegExp, string][] = [
  [/^Primary$/, "Hlavná"],
  [/^Primary (\d+)$/, "Hlavná $1"],
  [/^Logo$/, "Logo"],
  [/^Left Side$/, "Ľavá strana"],
  [/^Right Side$/, "Pravá strana"],
  [/^Combined$/, "Kombinovaná"],
  [/^Zone (\d+)$/, "Zóna $1"],
  [/^Mainboard$/, "Základná doska"],
  [/^Onboard$/, "Na doske"],
  [/^RGB Header (\d+)$/, "RGB konektor $1"],
  [/^ARGB Header (\d+)$/, "ARGB konektor $1"],
  [/^Addressable Header (\d+)$/, "ARGB konektor $1"],
  [/^All LEDs$/, "Všetky LED"],
  [/^Strip$/, "Pásik"],
  [/^Left$/, "Ľavý"],
  [/^Right$/, "Pravý"],
  [/^Left Rear$/, "Ľavý zadný"],
  [/^Right Rear$/, "Pravý zadný"],
];

export function translateZone(name: string, lang: "sk" | "en"): string {
  if (lang === "en") return name;
  for (const [re, out] of ZONES_SK) if (re.test(name)) return name.replace(re, out);
  return name;
}
