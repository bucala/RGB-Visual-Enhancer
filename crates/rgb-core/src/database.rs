#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn usb_ids_are_unique_and_well_formed() {
        let mut seen = HashSet::new();
        for d in DEVICES.iter().filter(|d| d.bus == Bus::Usb) {
            assert!(seen.insert(d.ids), "duplicate id {}", d.ids);
            let (vid, pid) = d.ids.split_once(':').expect("VID:PID");
            assert!(
                u16::from_str_radix(vid, 16).is_ok() && u16::from_str_radix(pid, 16).is_ok(),
                "{}",
                d.ids
            );
            assert!(
                d.match_key.ends_with(':') && d.match_key.contains(&pid.to_lowercase()),
                "{}",
                d.match_key
            );
        }
    }

    #[test]
    fn matches_what_the_drivers_produce() {
        let ids = [
            "logitech:046d:c332:serial:ff",
            "aura-usb:1939:\\\\?\\hid",
            "msi-gpu:2882:5160",
        ];
        for id in ids {
            assert!(
                DEVICES
                    .iter()
                    .any(|d| !d.match_key.is_empty() && id.starts_with(d.match_key)),
                "{id}"
            );
        }
        assert!(DEVICES.len() > 150);
    }
}

