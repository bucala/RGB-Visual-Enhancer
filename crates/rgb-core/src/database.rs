//! Known devices: what the app can (or plans to) control, with the ids it
//! matches on. Sources: OpenRGB detector tables and g810-led (ids only).
//! Support levels are deliberately conservative.

use serde::Serialize;

use crate::types::DeviceType;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Support {
    /// Confirmed on real hardware.
    Verified,
    /// Implemented; expected to work (same protocol as verified devices).
    Supported,
    /// Implemented but unconfirmed, or only partially.
    Experimental,
    /// Known model, not implemented yet.
    Planned,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Bus {
    Usb,
    Pci,
    Smbus,
    Ble,
}

#[derive(Clone, Copy, Debug, Serialize)]
pub struct KnownDevice {
    pub vendor: &'static str,
    pub name: &'static str,
    pub kind: DeviceType,
    pub bus: Bus,
    /// Human-readable ids (VID:PID, PCI ids, GATT service…).
    pub ids: &'static str,
    /// Prefix of the app's device id for connected-device matching
    /// (empty when the model can't be matched yet).
    pub match_key: &'static str,
    pub support: Support,
    pub note: Option<&'static str>,
}

